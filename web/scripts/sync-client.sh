#!/usr/bin/env bash
# Copies the browser package (app/src/client) and the shared core it imports (app/src/core) into src/vendor/ifso, so
# `web/` builds on its own (Vercel uses web/ as the root). Run after any change under those two folders; the test
# test/vendor-sync.test.ts fails when the copy is behind.
# The only edit: the AppRouter type points at the web app's own typed API (src/lib/ifso/api.ts), because the real router
# imports server code that must not be part of the site.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$here/../app/src"
dst="$here/src/vendor/ifso"
[ -d "$src/client" ] && [ -d "$src/core" ] || { echo "sync-client: app/src not found next to web/" >&2; exit 1; }
rm -rf "$dst"
mkdir -p "$dst/client" "$dst/core"
# only the core modules the browser package imports (parser, builder, bot copy and the rest are server business)
for f in condition geo link linkWallet paramsJson types typedData; do cp "$src/core/$f.ts" "$dst/core/$f.ts"; done
for f in claimPage copyRules index verifyBuild; do cp "$src/client/$f.ts" "$dst/client/$f.ts"; done
# portable in-place edit (BSD and GNU sed differ): rewrite through a temp file
tmp="$(mktemp)"
sed 's#^export type { AppRouter } from "../api/router";#export type { AppRouter } from "../../../lib/ifso/api";#' "$dst/client/index.ts" > "$tmp"
mv "$tmp" "$dst/client/index.ts"
printf "// GENERATED by web/scripts/sync-client.sh from app/src/client and app/src/core. Do not edit; edit the source and re-run.\n" > "$dst/GENERATED.txt"
echo "sync-client: copied $(ls "$dst/core" | wc -l) core files and 4 client files"

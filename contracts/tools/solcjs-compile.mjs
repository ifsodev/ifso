#!/usr/bin/env node
// Compile-check every .sol file (src/, test/, script/) with solc-js 0.8.28 via standard JSON.
// Usage: SOLC_PATH=/path/to/node_modules/solc node tools/solcjs-compile.mjs [--src-only] [--abi-out dir]
// Exists so the repo can be verified on machines without Foundry (forge) installed.
import { readFileSync, readdirSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve, dirname } from "node:path";
import { createRequire } from "node:module";

const root = resolve(dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(import.meta.url);
const solc = require(process.env.SOLC_PATH || "solc");
const srcOnly = process.argv.includes("--src-only");
const abiOutIdx = process.argv.indexOf("--abi-out");
const abiOut = abiOutIdx > 0 ? process.argv[abiOutIdx + 1] : null;
const tsOutIdx = process.argv.indexOf("--abi-ts-out");
const abiTsOut = tsOutIdx > 0 ? process.argv[tsOutIdx + 1] : null;
const TS_ABIS = ["IfsoEscrow", "IfsoConditionEvaluator", "IfsoOutcomeResolver", "FeeRouter"];

function walk(dir) {
  const out = [];
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (p.endsWith(".sol")) out.push(p);
  }
  return out;
}

const dirs = srcOnly ? ["src"] : ["src", "test", "script"];
const files = dirs.flatMap((d) => walk(join(root, d)));
const sources = Object.fromEntries(files.map((f) => [relative(root, f), { content: readFileSync(f, "utf8") }]));

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

function findImports(path) {
  try {
    return { contents: readFileSync(join(root, path), "utf8") };
  } catch {
    return { error: "File not found: " + path };
  }
}

console.log(`solc ${solc.version()} — compiling ${files.length} files`);
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors || []).filter((e) => e.severity === "error");
const isTestSizeWarning = (e) =>
  /code size|initcode size/.test(e.message) && /^(test|script)\//.test(e.sourceLocation?.file || "");
const expected = (out.errors || []).filter((e) => e.severity !== "error" && isTestSizeWarning(e));
const warnings = (out.errors || []).filter((e) => e.severity !== "error" && !isTestSizeWarning(e));
if (expected.length) console.log(`(${expected.length} expected size warnings on test/script contracts that deploy the full stack — Foundry ignores EIP-170 for test contracts)`);
for (const w of warnings) console.log("WARN:", w.formattedMessage.split("\n")[0]);
for (const e of errors) console.error(e.formattedMessage);

let n = 0;
const sizes = [];
for (const [file, contracts] of Object.entries(out.contracts || {})) {
  for (const [name, c] of Object.entries(contracts)) {
    n++;
    const size = (c.evm?.deployedBytecode?.object?.length || 0) / 2;
    if (file.startsWith("src/") && size > 0) sizes.push([name, size]);
    if (abiTsOut && file.startsWith("src/") && TS_ABIS.includes(name)) {
      mkdirSync(abiTsOut, { recursive: true });
      const constName = name[0].toLowerCase() + name.slice(1) + "Abi";
      writeFileSync(
        join(abiTsOut, `${name}.ts`),
        `// GENERATED by contracts/tools/solcjs-compile.mjs --abi-ts-out. Do not edit.\nexport const ${constName} = ${JSON.stringify(c.abi, null, 2)} as const;\n`,
      );
    }
    if (abiOut && file.startsWith("src/") && !file.includes("/mocks/")) {
      mkdirSync(abiOut, { recursive: true });
      writeFileSync(join(abiOut, `${name}.json`), JSON.stringify(c.abi, null, 2));
    }
  }
}
for (const [name, size] of sizes.sort((a, b) => b[1] - a[1])) console.log(`  ${name.padEnd(28)} ${size} bytes`);
console.log(`${errors.length} errors, ${warnings.length} warnings, ${n} contracts/interfaces/libraries compiled`);
process.exit(errors.length ? 1 : 0);
